// 与素材文件名一致:中文转 hex 码点(上.png -> 4e0a.png),纯 ASCII(panda)原样
function assetName(name) {
  return name
    .split('-')
    .map((part) =>
      /^[\x20-\x7e]*$/.test(part)
        ? part
        : [...part].map((ch) => ch.charCodeAt(0).toString(16)).join('')
    )
    .join('-')
}

